export const CURRENCY_OPTIONS = CURRENCIES.map(([code, name]) => ({
  value: code,
  label: `${code} — ${name}`,
}));

/** Короткий список для поля рядом с суммой: только используемые в поездке. */
export function currencyOptionsFor(codes) {
  const set = [...new Set(codes)];
  return set.map((c) => ({ value: c, label: c }));
}

export function currencyName(code) {
  const row = CURRENCIES.find(([c]) => c === code);
  return row ? row[1] : code;
}
